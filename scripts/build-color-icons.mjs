// Writes the drawings of the optional icon packs for the emoji the interface uses (Settings › Appearance › Icons):
//   src/icons-color.js     Fluent Emoji Flat (Microsoft, MIT)          – by emoji, from the table in src/icons.js
//   src/icons-material.js  Material Symbols Rounded (Google, Apache-2.0) – names in src/icon-names.js
//   src/icons-duotone.js   Phosphor Duotone (Phosphor Icons, MIT)        – names in src/icon-names.js
// Run after changing either table:  node scripts/build-color-icons.mjs
import { readFileSync, writeFileSync } from 'node:fs';
import { createRequire } from 'node:module';
import names from '../src/icon-names.js';
const require = createRequire(import.meta.url);

const write = (file, credit, viewBox, out) =>
  writeFileSync(
    new URL(`../src/${file}`, import.meta.url),
    `// Generated by scripts/build-color-icons.mjs – do not edit.\n// ${credit}\n// key -> the inside of an <svg viewBox="${viewBox}">\nexport const viewBox = '${viewBox}';\nexport default {\n${Object.entries(out)
      .sort()
      .map(([k, b]) => `  ${JSON.stringify(k)}: ${JSON.stringify(b)},`)
      .join('\n')}\n};\n`,
  );

// 1. colourful: by emoji
{
  const set = require('@iconify-json/fluent-emoji-flat/icons.json');
  const chars = require('@iconify-json/fluent-emoji-flat/chars.json');
  const src = readFileSync(new URL('../src/icons.js', import.meta.url), 'utf8');
  const table = src.slice(src.indexOf('const MAP = {'), src.indexOf('// end of the table'));
  const wanted = new Set([...table.matchAll(/'([^'\\]{1,4})'/g)].map((m) => m[1]).filter((s) => /[^\x00-\x7F]/.test(s)));
  const hex = (s) => [...s].map((c) => c.codePointAt(0).toString(16)).join('-');
  const out = {};
  const missing = [];
  for (const e of wanted) {
    const name = chars[hex(e)] || chars[hex(e + '\uFE0F')] || chars[hex(e.replace(/\uFE0F/g, ''))];
    const icon = name && (set.icons[name] || set.icons[set.aliases?.[name]?.parent]);
    if (icon) out[e.replace(/\uFE0F/g, '')] = icon.body;
    else missing.push(e);
  }
  write('icons-color.js', 'Fluent Emoji Flat, (c) Microsoft Corporation, MIT licence: https://github.com/microsoft/fluentui-emoji', '0 0 32 32', out);
  console.log(`colourful: ${Object.keys(out).length}; none for ${missing.join(' ') || '-'}`);
}

// 2 and 3: by name
for (const [file, pkg, col, pick, credit] of [
  ['icons-material.js', '@iconify-json/material-symbols', 0, (n) => [`${n}-outline-rounded`, `${n}-rounded`, n], 'Material Symbols Rounded (outlined where there is one), (c) Google, Apache License 2.0: https://github.com/google/material-design-icons'],
  ['icons-duotone.js', '@iconify-json/ph', 1, (n) => [`${n}-duotone`], 'Phosphor Icons (duotone), (c) Phosphor Icons, MIT licence: https://github.com/phosphor-icons/core'],
]) {
  const set = require(`${pkg}/icons.json`);
  const out = {};
  const missing = [];
  for (const [key, pair] of Object.entries(names)) {
    const hit = pick(pair[col]).map((n) => set.icons[n] || set.icons[set.aliases?.[n]?.parent]).find(Boolean);
    if (hit) out[key] = hit.body;
    else missing.push(`${key}=${pair[col]}`);
  }
  write(file, credit, `0 0 ${set.width} ${set.height}`, out);
  console.log(`${file}: ${Object.keys(out).length}; missing ${missing.join(' ') || '-'}`);
}
