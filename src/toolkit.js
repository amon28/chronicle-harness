// One home for every helper script the shell gets. The files in ./toolkit/ are the source of truth:
// they are shipped with the app, injected into the built-in Linux on first use, and verified by hash on
// every shell start. A drifted copy in /usr/local/bin is overwritten, not trusted - two versions of a
// tool is worse than none. 'toolkit-pull' can re-fetch the same files from a static URL after a re-image.
import jobBody from './toolkit/job?raw';
import doctorBody from './toolkit/doctor?raw';
import pullBody from './toolkit/toolkit-pull?raw';
import bridgeBody from './toolkit/mcp-bridge?raw';
import { sha256Hex } from './hash.js';

/** Where the scripts live inside the shell. In PATH, so 'job', 'doctor' and 'toolkit-pull' just work. */
export const TOOLKIT_DIR = '/usr/local/bin';
/** Bump when a script changes in a way the verifier must not paper over (the hashes do the real check). */
export const TOOLKIT_VERSION = 1;

export const TOOLKIT_FILES = [
  { name: 'job', body: jobBody },
  { name: 'doctor', body: doctorBody },
  { name: 'toolkit-pull', body: pullBody },
  { name: 'mcp-bridge', body: bridgeBody },
];

/** A script body as the shell should see it: LF endings, exactly one trailing newline. */
export const normalise = (s) => String(s).replace(/\r\n/g, '\n').replace(/[ \t]+$/gm, '').replace(/\n+$/, '') + '\n';

export { sha256Hex };

let metaPromise = null;
/** [{ name, body, sha256, path }] - computed once. */
export function toolkitMeta() {
  metaPromise ||= Promise.all(
    TOOLKIT_FILES.map(async (f) => {
      const body = normalise(f.body);
      return { name: f.name, body, sha256: await sha256Hex(body), path: `${TOOLKIT_DIR}/${f.name}` };
    }),
  );
  return metaPromise;
}

const q = (s) => `'${String(s).replace(/'/g, "'\\''")}'`;

/** The one command that installs (or repairs) the whole toolkit and prints what it wrote, with hashes. */
export async function toolkitInstallCommand() {
  const files = await toolkitMeta();
  const lines = [`mkdir -p ${q(TOOLKIT_DIR)}`];
  for (const f of files) {
    const delim = `OCM_EOF_${f.name.replace(/[^A-Za-z0-9]/g, '_')}`;
    if (f.body.includes(delim)) throw new Error(`The ${f.name} script contains its own heredoc marker`);
    lines.push(`cat > ${q(f.path)} <<'${delim}'`, f.body.replace(/\n$/, ''), delim, `chmod 755 ${q(f.path)}`);
  }
  const manifest = [`# generated by the app (toolkit v${TOOLKIT_VERSION}) - do not edit`, ...files.map((f) => `${f.sha256}  ${f.name}`)].join('\n');
  lines.push(`cat > ${q(`${TOOLKIT_DIR}/.toolkit`)} <<'OCM_EOF_MANIFEST'`, manifest, 'OCM_EOF_MANIFEST');
  lines.push(`cd ${q(TOOLKIT_DIR)} && sha256sum ${files.map((f) => q(f.name)).join(' ')}`);
  return lines.join('\n');
}

/**
 * Read back the hashes of the installed scripts (nothing is written), and whether they are executable:
 * a correct hash on a file nobody can run is a green tick that lies.
 */
export async function toolkitVerifyCommand() {
  const files = await toolkitMeta();
  const names = files.map((f) => q(f.name)).join(' ');
  return `cd ${q(TOOLKIT_DIR)} 2>/dev/null && sha256sum ${names} 2>/dev/null; for n in ${names}; do [ -x "$n" ] || echo "not-executable $n"; done`;
}

/** "hash  path" lines (GNU and busybox) -> { name: hash }. */
export function parseSha256(text) {
  const out = {};
  for (const line of String(text || '').split('\n')) {
    const m = /^([0-9a-f]{64})\s+\*?(.+?)\s*$/i.exec(line.trim());
    if (m) out[m[2].split('/').pop()] = m[1].toLowerCase();
  }
  return out;
}

/**
 * Check the installed toolkit and repair anything missing or changed.
 * exec(cmd) => { output, exit }: one command in the chat's shell.
 * Returns { ok, repaired, files: { name: { ok, sha256 } }, error }.
 */
export async function ensureToolkit(exec, { force = false } = {}) {
  const files = await toolkitMeta();
  const expected = Object.fromEntries(files.map((f) => [f.name, f.sha256]));
  const inspect = async () => {
    const r = await exec(await toolkitVerifyCommand());
    const got = parseSha256(r.output);
    const notExec = new Set([...String(r.output || '').matchAll(/not-executable\s+(\S+)/g)].map((m) => m[1]));
    const out = {};
    for (const f of files) out[f.name] = { ok: got[f.name] === f.sha256 && !notExec.has(f.name), sha256: got[f.name] || null };
    return out;
  };
  let state = force ? null : await inspect().catch(() => null);
  if (state && files.every((f) => state[f.name].ok)) return { ok: true, repaired: false, files: state };
  const install = await exec(await toolkitInstallCommand());
  state = await inspect();
  const ok = files.every((f) => state[f.name].ok);
  return {
    ok,
    repaired: true,
    files: state,
    error: ok ? null : `The toolkit did not verify after installing${install.exit ? ` (exit ${install.exit})` : ''}: ` + files.filter((f) => !state[f.name].ok).map((f) => `${f.name}=${state[f.name].sha256 || 'missing'} (want ${expected[f.name]})`).join(', '),
  };
}

/** One line for a result header: "toolkit job=1a2b3c4d doctor=… (verified)". */
export function toolkitSummary(state) {
  if (!state) return 'toolkit unknown';
  const names = Object.keys(state.files || {});
  const bad = names.filter((n) => !state.files[n].ok);
  return `toolkit ${names.map((n) => `${n}=${(state.files[n].sha256 || 'missing').slice(0, 8)}`).join(' ')} ${bad.length ? `DRIFT(${bad.join(',')})` : 'verified'}`;
}