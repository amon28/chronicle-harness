import { describe, it, expect } from 'vitest';
import { toolkitMeta, toolkitInstallCommand, toolkitVerifyCommand, parseSha256, ensureToolkit, normalise, toolkitSummary, TOOLKIT_DIR } from '../../src/toolkit.js';

describe('one toolkit, one home', () => {
  it('ships the scripts with stable, real hashes', async () => {
    const files = await toolkitMeta();
    expect(files.map((f) => f.name)).toEqual(['job', 'doctor', 'toolkit-pull', 'mcp-bridge']);
    for (const f of files) {
      expect(f.sha256).toMatch(/^[0-9a-f]{64}$/);
      expect(f.body.startsWith(f.name === 'mcp-bridge' ? '#!/usr/bin/env python3' : '#!/bin/sh')).toBe(true);
      expect(f.body.endsWith('\n')).toBe(true);
      expect(f.path).toBe(TOOLKIT_DIR + '/' + f.name);
    }
    // and the same bytes hash the same way twice
    const again = await toolkitMeta();
    expect(again.map((f) => f.sha256)).toEqual(files.map((f) => f.sha256));
  });

  it('normalises line endings and trailing space, so a copy cannot drift by accident', () => {
    expect(normalise('a\r\n b  \r\n\n\n')).toBe('a\n b\n');
    expect(normalise('x')).toBe('x\n');
  });

  it('installs each script through a heredoc and records a manifest with hashes', async () => {
    const cmd = await toolkitInstallCommand();
    expect(cmd).toContain("mkdir -p '/usr/local/bin'");
    expect(cmd).toContain("cat > '/usr/local/bin/job' <<'OCM_EOF_job'");
    expect(cmd).toContain("chmod 755 '/usr/local/bin/job'");
    expect(cmd).toContain("cat > '/usr/local/bin/.toolkit' <<'OCM_EOF_MANIFEST'");
    const files = await toolkitMeta();
    for (const f of files) expect(cmd).toContain(f.sha256 + '  ' + f.name);
    expect(cmd).toContain('sha256sum');
  });

  it('reads sha256sum output from GNU and busybox alike', () => {
    const h = 'a'.repeat(64);
    expect(parseSha256(h + '  ./usr/local/bin/job\n')).toMatchObject({ job: h });
    expect(parseSha256(h + '  /usr/local/bin/doctor')).toMatchObject({ doctor: h });
    expect(parseSha256('garbage')).toEqual({});
  });

  it('verifies what is installed and repairs a drifted copy instead of trusting it', async () => {
    const files = await toolkitMeta();
    let installed = {};
    const exec = async (cmd) => {
      if (cmd.includes("cat > '/usr/local/bin/job'")) {
        for (const f of files) installed[f.name] = f.sha256;
        return { output: '', exit: 0 };
      }
      if (cmd.includes("sha256sum 'job'")) {
        const lines = files.filter((f) => installed[f.name]).map((f) => installed[f.name] + '  ' + f.name);
        return { output: lines.join('\n'), exit: 0 };
      }
      return { output: '', exit: 0 };
    };
    const first = await ensureToolkit(exec, { force: true });
    expect(first.ok).toBe(true);
    expect(first.repaired).toBe(true);

    const quiet = await ensureToolkit(exec);
    expect(quiet.ok).toBe(true);
    expect(quiet.repaired).toBe(false);

    installed.doctor = 'f'.repeat(64); // someone edited the visible copy
    const repaired = await ensureToolkit(exec);
    expect(repaired.repaired).toBe(true);
    expect(repaired.ok).toBe(true);
    expect(installed.doctor).toBe(files.find((f) => f.name === 'doctor').sha256);

    expect((await toolkitVerifyCommand())).toContain('sha256sum');
    expect(toolkitSummary(repaired)).toMatch(/job=[0-9a-f]{8}/);
    expect(toolkitSummary(repaired)).toContain('verified');
    expect(toolkitSummary({ files: { job: { ok: false, sha256: null } } })).toContain('DRIFT');
  });

  it('the manifest header is a comment, not a script, and a bad line is reported', async () => {
    const files = await toolkitMeta();
    const body = files.find((f) => f.name === 'toolkit-pull').body;
    // the app writes "# generated by the app (toolkit v1) - do not edit" as the first line of
    // /usr/local/bin/.toolkit; pulling "generated" as a fourth script was the bug
    expect(body).toContain('/^[[:space:]]*#/ { next }');
    // a line is only an entry when field 1 is a sha256 and there are exactly two fields
    expect(body).toContain('NF == 2');
    expect(body).toContain('length($1) == 64');
    expect(body).toContain('bad manifest line');
    // a pull that did not work must say so in the exit code
    expect(body).toMatch(/exit 1/);
  });
});

describe('doctor says which network failure it was (decision 269)', () => {
  it('a name that does not exist is FAILED with a reason, never one BLOCKED for every kind of failure', async () => {
    const { execFileSync } = await import('node:child_process');
    const { fileURLToPath } = await import('node:url');
    const script = fileURLToPath(new URL('../../src/toolkit/doctor', import.meta.url));
    const out = execFileSync('sh', [script], { env: { ...process.env, DOCTOR_HOSTS: 'nonexistent.invalid' }, encoding: 'utf8', timeout: 30000 });
    expect(out).toMatch(/^net nonexistent\.invalid\s+FAILED/m);
    expect(out).not.toMatch(/BLOCKED/);
  }, 40000);
});
